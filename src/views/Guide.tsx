/** A screenshot from public/guide (made by `npm run guide:shots` from the demo data). */
function Shot({ name, phone, caption }: { name: string; phone?: boolean; caption: ReactNode }) {
  return (
    <figure className={`gshot ${phone ? 'phone' : 'wide'}`}>
      <img
        src={`/guide/${name}.webp`}
        alt={typeof caption === 'string' ? caption : ''}
        loading="lazy"
        decoding="async"
      />
      <figcaption>{caption}</figcaption>
    </figure>
  );
}

function Step({ id, title, children }: { id: string; title: string; children: ReactNode }) {
  return (
    <section className="gstep" id={id}>
      <h3>{title}</h3>
      {children}
    </section>
  );
}

